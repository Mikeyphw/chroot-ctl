package contractgen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type contract struct {
	ContractSchemaVersion int        `json:"contractSchemaVersion"`
	Program               string     `json:"program"`
	GlobalArguments       []argument `json:"globalArguments"`
	CommandNodes          []command  `json:"commandNodes"`
}

type argument struct {
	Dest          string          `json:"dest"`
	OptionStrings []string        `json:"optionStrings"`
	Action        string          `json:"action"`
	NArgs         json.RawMessage `json:"nargs"`
	Default       json.RawMessage `json:"default"`
	Choices       []string        `json:"choices"`
	Type          *string         `json:"type"`
	Required      bool            `json:"required"`
	Help          *string         `json:"help"`
	Completion    string          `json:"completion"`
	Minimum       json.RawMessage `json:"minimum"`
	Maximum       json.RawMessage `json:"maximum"`
}

type privilegeRule struct {
	AnyTrue []string `json:"anyTrue"`
	Level   string   `json:"level"`
}

type command struct {
	Command            string          `json:"command"`
	Path               []string        `json:"path"`
	Description        *string         `json:"description"`
	Epilog             *string         `json:"epilog"`
	Arguments          []argument      `json:"arguments"`
	Handler            string          `json:"handler"`
	Group              bool            `json:"group"`
	Hidden             bool            `json:"hidden"`
	CompletionExposed  bool            `json:"completionExposed"`
	OutputModes        []string        `json:"outputModes"`
	StreamMode         string          `json:"streamMode"`
	Privilege          string          `json:"privilege"`
	Mutability         string          `json:"mutability"`
	HealthExitPolicy   string          `json:"healthExitPolicy"`
	ExclusiveGroups    [][]string      `json:"exclusiveGroups"`
	RequireOneOfGroups [][]string      `json:"requireOneOfGroups"`
	JSONForbiddenWhen  []string        `json:"jsonForbiddenWhen"`
	PrivilegeRules     []privilegeRule `json:"privilegeRules"`
}

type Generated struct {
	Go   []byte
	Docs []byte
}

func Generate(root string) (Generated, error) {
	path := filepath.Join(root, "migration", "contracts", "v1", "cli.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		return Generated{}, err
	}
	var c contract
	if err = json.Unmarshal(raw, &c); err != nil {
		return Generated{}, fmt.Errorf("decode CLI contract: %w", err)
	}
	if c.Program == "" || len(c.CommandNodes) == 0 {
		return Generated{}, fmt.Errorf("CLI contract is incomplete")
	}
	digest := sha256.Sum256(raw)
	goSource, err := generateGo(c, hex.EncodeToString(digest[:]))
	if err != nil {
		return Generated{}, err
	}
	return Generated{Go: goSource, Docs: generateDocs(c, hex.EncodeToString(digest[:]))}, nil
}

func Write(root string) error {
	g, err := Generate(root)
	if err != nil {
		return err
	}
	outputs := []struct {
		path string
		data []byte
	}{
		{filepath.Join(root, "internal", "clicontract", "specs_generated.go"), g.Go},
		{filepath.Join(root, "docs", "cli", "COMMAND_REFERENCE.md"), g.Docs},
	}
	for _, out := range outputs {
		if err := os.MkdirAll(filepath.Dir(out.path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(out.path, out.data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func Check(root string) error {
	g, err := Generate(root)
	if err != nil {
		return err
	}
	checks := []struct {
		path string
		want []byte
	}{
		{filepath.Join(root, "internal", "clicontract", "specs_generated.go"), g.Go},
		{filepath.Join(root, "docs", "cli", "COMMAND_REFERENCE.md"), g.Docs},
	}
	for _, check := range checks {
		got, err := os.ReadFile(check.path)
		if err != nil {
			return err
		}
		if !bytes.Equal(got, check.want) {
			return fmt.Errorf("generated CLI artifact is stale: %s; run `go run ./cmd/cli-contract-gen`", filepath.ToSlash(check.path))
		}
	}
	return nil
}

func generateGo(c contract, digest string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/cli-contract-gen from migration/contracts/v1/cli.json; DO NOT EDIT.\n")
	b.WriteString("package clicontract\n\n")
	fmt.Fprintf(&b, "const ContractSHA256 = %s\n", strconv.Quote(digest))
	fmt.Fprintf(&b, "const ContractSchemaVersion = %d\n", c.ContractSchemaVersion)
	fmt.Fprintf(&b, "const Program = %s\n\n", strconv.Quote(c.Program))
	b.WriteString("var GlobalArguments = []ArgumentSpec{\n")
	for _, a := range c.GlobalArguments {
		fmt.Fprintf(&b, "\t%s,\n", renderArgument(a))
	}
	b.WriteString("}\n\nvar CommandSpecs = []CommandSpec{\n")
	for _, cmd := range c.CommandNodes {
		fmt.Fprintf(&b, "\t%s,\n", renderCommand(cmd))
	}
	b.WriteString("}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated CLI contract: %w", err)
	}
	return formatted, nil
}

func renderCommand(c command) string {
	args := make([]string, 0, len(c.Arguments))
	for _, a := range c.Arguments {
		args = append(args, renderArgument(a))
	}
	rules := make([]string, 0, len(c.PrivilegeRules))
	for _, r := range c.PrivilegeRules {
		rules = append(rules, fmt.Sprintf("{AnyTrue:%s,Level:%s}", stringSlice(r.AnyTrue), strconv.Quote(r.Level)))
	}
	return fmt.Sprintf("{Command:%s,Path:%s,Description:%s,Epilog:%s,Arguments:[]ArgumentSpec{%s},Handler:%s,Group:%t,Hidden:%t,CompletionExposed:%t,OutputModes:%s,StreamMode:%s,Privilege:%s,Mutability:%s,HealthExitPolicy:%s,ExclusiveGroups:%s,RequireOneOfGroups:%s,JSONForbiddenWhen:%s,PrivilegeRules:[]PrivilegeRule{%s}}",
		strconv.Quote(c.Command), stringSlice(c.Path), quotePtr(c.Description), quotePtr(c.Epilog), strings.Join(args, ","), strconv.Quote(c.Handler), c.Group, c.Hidden, c.CompletionExposed, stringSlice(c.OutputModes), strconv.Quote(c.StreamMode), strconv.Quote(c.Privilege), strconv.Quote(c.Mutability), strconv.Quote(c.HealthExitPolicy), stringGroups(c.ExclusiveGroups), stringGroups(c.RequireOneOfGroups), stringSlice(c.JSONForbiddenWhen), strings.Join(rules, ","))
}

func renderArgument(a argument) string {
	return fmt.Sprintf("{Dest:%s,Options:%s,Action:%s,NArgs:%s,Default:%s,Choices:%s,Type:%s,Required:%t,Help:%s,Completion:%s,Minimum:%s,Maximum:%s}",
		strconv.Quote(a.Dest), stringSlice(a.OptionStrings), strconv.Quote(a.Action), rawGo(a.NArgs), rawGo(a.Default), stringSlice(a.Choices), strconv.Quote(ptrValue(a.Type)), a.Required, strconv.Quote(ptrValue(a.Help)), strconv.Quote(a.Completion), rawGo(a.Minimum), rawGo(a.Maximum))
}

func rawGo(raw json.RawMessage) string {
	text := strings.TrimSpace(string(raw))
	if text == "" || text == "null" {
		return "nil"
	}
	var value any
	if json.Unmarshal(raw, &value) != nil {
		return "nil"
	}
	switch v := value.(type) {
	case string:
		return strconv.Quote(v)
	case bool:
		if v {
			return "true"
		}
		return "false"
	case float64:
		return strconv.FormatFloat(v, 'f', -1, 64)
	case []any:
		parts := make([]string, 0, len(v))
		for _, item := range v {
			encoded, _ := json.Marshal(item)
			parts = append(parts, rawGo(encoded))
		}
		return "[]any{" + strings.Join(parts, ",") + "}"
	default:
		return "nil"
	}
}
func ptrValue(v *string) string {
	if v == nil {
		return ""
	}
	return *v
}
func quotePtr(v *string) string { return strconv.Quote(ptrValue(v)) }
func stringSlice(values []string) string {
	parts := make([]string, 0, len(values))
	for _, v := range values {
		parts = append(parts, strconv.Quote(v))
	}
	return "[]string{" + strings.Join(parts, ",") + "}"
}
func stringGroups(groups [][]string) string {
	parts := make([]string, 0, len(groups))
	for _, g := range groups {
		parts = append(parts, stringSlice(g))
	}
	return "[][]string{" + strings.Join(parts, ",") + "}"
}

func generateDocs(c contract, digest string) []byte {
	var b strings.Builder
	b.WriteString("# chrootctl command reference\n\n")
	b.WriteString("Generated from `migration/contracts/v1/cli.json`. Do not edit this file directly.\n\n")
	fmt.Fprintf(&b, "Contract SHA-256: `%s`\n\n", digest)
	b.WriteString("Global options may appear before or after a command. When a command-local option uses the same spelling, the command-local option wins.\n\n")
	b.WriteString("## Global options\n\n| Option | Required | Description |\n|---|---:|---|\n")
	for _, a := range c.GlobalArguments {
		fmt.Fprintf(&b, "| `%s` | %t | %s |\n", strings.Join(a.OptionStrings, "`, `"), a.Required, escapeTable(ptrValue(a.Help)))
	}
	b.WriteString("\n## Commands\n")
	for _, cmd := range c.CommandNodes {
		if cmd.Hidden {
			continue
		}
		fmt.Fprintf(&b, "\n### `%s`\n\n%s\n\n", cmd.Command, ptrValue(cmd.Description))
		fmt.Fprintf(&b, "- Output modes: `%s`\n- Privilege: `%s`\n- Mutability: `%s`\n", strings.Join(cmd.OutputModes, "`, `"), cmd.Privilege, cmd.Mutability)
		if cmd.HealthExitPolicy != "" && cmd.HealthExitPolicy != "informational" {
			fmt.Fprintf(&b, "- Health exit policy: `%s`\n", cmd.HealthExitPolicy)
		}
		if len(cmd.ExclusiveGroups) > 0 {
			for _, g := range cmd.ExclusiveGroups {
				fmt.Fprintf(&b, "- Mutually exclusive: `%s`\n", strings.Join(g, "`, `"))
			}
		}
		if len(cmd.Arguments) > 0 {
			b.WriteString("\n| Argument | Required | Repeatable | Description |\n|---|---:|---:|---|\n")
			for _, a := range cmd.Arguments {
				if ptrValue(a.Help) == "<SUPPRESS>" {
					continue
				}
				name := a.Dest
				if len(a.OptionStrings) > 0 {
					name = strings.Join(a.OptionStrings, "`, `")
				}
				fmt.Fprintf(&b, "| `%s` | %t | %t | %s |\n", name, a.Required, a.Action == "_AppendAction", escapeTable(ptrValue(a.Help)))
			}
		}
		if ep := strings.TrimSpace(ptrValue(cmd.Epilog)); ep != "" {
			b.WriteString("\n```text\n" + ep + "\n```\n")
		}
	}
	return []byte(b.String())
}
func escapeTable(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ")
}

func Commands(candidates []string) []string {
	out := append([]string(nil), candidates...)
	sort.Strings(out)
	return out
}
