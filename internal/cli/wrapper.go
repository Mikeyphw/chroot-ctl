package cli

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"chrootctl/internal/completion"
)

const defaultWrapperName = "chc"

// InstallWrapper installs a small local shell wrapper that preserves the user's
// current directory, PATH, and argv, then uses su -c only when the caller is not
// already root. The wrapper is deliberately shell-only so it works before any
// Python or Termux package setup is available.
func InstallWrapper(inv Invocation, stdout, stderr io.Writer) int {
	home, err := os.UserHomeDir()
	if err != nil || home == "" {
		home = os.Getenv("HOME")
	}
	if home == "" {
		fmt.Fprintln(stderr, "chrootctl: cannot determine home directory for wrapper install")
		return 1
	}
	name := strings.TrimSpace(inv.String("wrapper_name"))
	if name == "" {
		name = defaultWrapperName
	}
	if strings.Contains(name, "/") || strings.Contains(name, "\\") || strings.ContainsRune(name, 0) || name == "." || name == ".." {
		fmt.Fprintf(stderr, "chrootctl: invalid wrapper name: %s\n", name)
		return 2
	}
	dir := strings.TrimSpace(inv.String("wrapper_dir"))
	if dir == "" {
		dir = filepath.Join(home, ".local", "bin")
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(stderr, "chrootctl:", err)
		return 1
	}
	wrapperPath := filepath.Join(dir, name)
	if err := atomicWriteExecutable(wrapperPath, []byte(wrapperScript())); err != nil {
		fmt.Fprintln(stderr, "chrootctl:", err)
		return 1
	}
	fmt.Fprintf(stdout, "Installed wrapper: %s\n", wrapperPath)

	completionDir := strings.TrimSpace(inv.String("completion_dir"))
	if completionDir == "" && !inv.Bool("no_completion") {
		candidate := filepath.Join(home, ".local", "share", "zsh", "site-functions")
		if st, err := os.Stat(candidate); err == nil && st.IsDir() {
			completionDir = candidate
		}
	}
	if completionDir != "" && !inv.Bool("no_completion") {
		if err := os.MkdirAll(completionDir, 0o755); err != nil {
			fmt.Fprintln(stderr, "chrootctl:", err)
			return 1
		}
		completionPath := filepath.Join(completionDir, "_chrootctl")
		if err := atomicWriteFile(completionPath, []byte(completion.GenerateZsh()), 0o644); err != nil {
			fmt.Fprintln(stderr, "chrootctl:", err)
			return 1
		}
		fmt.Fprintf(stdout, "Installed zsh completion: %s\n", completionPath)
	}
	fmt.Fprintf(stdout, "Use: %s --help\n", name)
	return 0
}

func atomicWriteExecutable(path string, data []byte) error {
	return atomicWriteFile(path, data, 0o755)
}

func atomicWriteFile(path string, data []byte, mode os.FileMode) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+"-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err = tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err = tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if err = tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	if err = os.Rename(tmpName, path); err != nil {
		return err
	}
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		_ = d.Close()
	}
	return nil
}

func wrapperScript() string {
	return `#!/system/bin/sh
# chrootctl local elevation wrapper. Generated by: chrootctl wrapper install
set -u

_chc_quote() {
  printf "'"
  printf "%s" "$1" | sed "s/'/'\\\\''/g"
  printf "'"
}

_chc_find_chrootctl() {
  _chc_self="${0:-}"
  _chc_found=$(command -v chrootctl 2>/dev/null || true)
  if [ -n "$_chc_found" ] && [ "$_chc_found" != "$_chc_self" ] && [ -x "$_chc_found" ]; then
    printf '%s\n' "$_chc_found"
    return 0
  fi
  for candidate in \
    /system/bin/chrootctl \
    /data/adb/modules/chrootctl-magisk/system/bin/chrootctl \
    /data/adb/modules_update/chrootctl-magisk/system/bin/chrootctl \
    /data/adb/ksu/modules/chrootctl-magisk/system/bin/chrootctl \
    /data/adb/ksu/modules_update/chrootctl-magisk/system/bin/chrootctl
  do
    if [ -x "$candidate" ]; then
      printf '%s\n' "$candidate"
      return 0
    fi
  done
  return 1
}

_chc_bin=$(_chc_find_chrootctl) || {
  echo "chc: chrootctl not found" >&2
  exit 127
}

if [ "$(id -u 2>/dev/null || echo 99999)" = "0" ]; then
  exec "$_chc_bin" "$@"
fi

_chc_path=${PATH:-/data/data/com.termux/files/usr/bin:/system/bin:/system/xbin:/vendor/bin}
_chc_cwd=$(pwd 2>/dev/null || printf '/')
_chc_cmd="export PATH=$(_chc_quote "$_chc_path"); cd $(_chc_quote "$_chc_cwd") && exec $(_chc_quote "$_chc_bin")"
for _chc_arg in "$@"; do
  _chc_cmd="$_chc_cmd $(_chc_quote "$_chc_arg")"
done
exec su -c "$_chc_cmd"
`
}
